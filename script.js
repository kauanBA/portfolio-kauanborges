function applyLanguage(language) {
  const selected = translations[language] ? language : 'pt';
  currentLanguage = selected;
  document.documentElement.lang = selected === 'pt' ? 'pt-BR' : selected;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[selected][key];
    if (typeof value === 'string') element.textContent = value;
  });

  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === selected));
  });

  messageIndex = 0;
  updateAssistantMessage();
  const menuToggle = document.getElementById('menuToggle');
  const nav = document.getElementById('primaryNav');
  if (nav && menuToggle) {
    nav.classList.remove('open');
    menuToggle.setAttribute('aria-expanded', 'false');
  }
}

function updateAssistantMessage() {
  const bubble = document.querySelector('#assistantBubble [data-i18n="assistant.greeting"]');
  if (!bubble) return;
  bubble.textContent = translations[currentLanguage].messages[messageIndex % translations[currentLanguage].messages.length];
}

document.querySelectorAll('[data-lang]').forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

